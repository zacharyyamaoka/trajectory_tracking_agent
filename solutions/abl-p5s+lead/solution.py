"""abl-p5s+lead: an ablation variant of p5s-pass3 (study ablations/pass3-2026-11-24.md). Add-one-in: p5s plus minus the board lead only.

Parent p5s. Kept: lead. Left out: bus, fric, chord, grav, fric2, stiff, vlag, reid.
Identification passes in model.json: none (frozen: p5s-pass3's own weights, never refitted here).
Generated by ablations/pass3-2026-11-24/make_variant.py: each kept component's code is p5s-pass3's own; its WHY
is in the solution that introduced it (lead p5s-bus-enc).
"""

from __future__ import annotations

import dataclasses

from robot_controllers.bench.arms import arm as registered_arm
from robot_controllers.bench.population import lookahead_for
from robot_controllers.bench.scenarios import base_scenario
from robot_controllers.controllers.layout import LayoutConfig, LayoutController
from robot_controllers.models import Layout

KP_SCALE = 1.0
KD_SCALE = 1.0


def build(trajectory, deployment):
    """A robot_controllers LayoutController (a robot_msgs JointController) for `trajectory` on `deployment`."""
    scenario = dataclasses.replace(
        base_scenario(deployment.arm), host_rate_hz=deployment.host_rate_hz, bus=deployment.bus
    )
    board = deployment.board
    period_s = 1.0 / deployment.host_rate_hz
    feedforward = registered_arm(deployment.arm).feedforward("rigid_body_coulomb", scenario.model_error)
    board_lead_s = board.encoder_delay_s + 1.0 / board.rate_hz  # 0.5 ms + 0.25 ms
    calibrated_s = lookahead_for("P5s", scenario)  # robot_controllers' calibrated lookahead (p5s's)
    lookahead_s = tuple(max(0.0, float(delay) - board_lead_s) for delay in calibrated_s)
    layout = Layout("plan", "board", lookahead_s=lookahead_s, interpolation="secant_mid_ff")
    config = LayoutConfig(feedforward=feedforward, feedback=None, layout=layout, control_period_s=period_s)
    return LayoutController(trajectory, config)
